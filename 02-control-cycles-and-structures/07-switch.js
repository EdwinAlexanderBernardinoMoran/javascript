const dayWeek = 0;

switch( dayWeek ) {
    case 0: // Sunday
        console.log('Sunday - We are open at 9am');
        break;
    case 1: // Monday
        console.log('Monday - We are open at 9am');
        break;
    case 2: // Tuesday
        console.log('Tuesday - We are open at 9am');
        break;
    case 3: // Wednesday
        console.log('Wednesday - We are open at 9am');
        break;
    case 4: // Thursday
        console.log('Thursday - We are open at 9am');
        break;
    case 5: // Friday
        console.log('Friday - We are open at 9am');
        break;
    case 6: // Saturday
        console.log('Saturday - We are open at 9am');
        break;
    default:
        console.log('Something went wrong!');
}